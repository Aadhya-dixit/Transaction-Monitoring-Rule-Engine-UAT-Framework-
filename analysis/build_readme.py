"""Generate README.md from the artefacts in reports/.

Every number in the README comes from a CSV/JSON produced by the pipeline, so
the documentation cannot drift away from the run. Do not edit README.md by
hand -- re-run this instead.

    python -m analysis.build_readme
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from engine.rule_engine import load_rules

RATIONALE = {
    "R01": "Classic mule / authorised-push-payment setup: first payment to a fresh beneficiary at an unusual size.",
    "R02": "Account takeover: a compromised session fires several transfers in minutes, faster than a human types.",
    "R03": "Automated fraud tooling runs off-hours. Genuine customers do pay at night, which is the main source of false positives.",
    "R04": "Card testing: repeated failures followed by one success suggests a working credential was found.",
    "R05": "Staying just under the reporting threshold to avoid a filing obligation.",
    "R06": "Device substitution plus a large debit is the strongest single signal of a hijacked session.",
    "R07": "Impossible travel: two locations inside a window the customer cannot physically cross.",
    "R08": "Fan-out to a single beneficiary, typical of mule-account collection.",
}


def pct(x) -> str:
    return f"{x:.1f}%"


def money(n) -> str:
    return f"{n:,.0f}"


def condition(rule: dict) -> str:
    t, p = rule["type"], rule["params"]
    if t == "high_amount_new_beneficiary":
        return f"amount > {money(p['amount_threshold'])} and is_new_beneficiary = 1"
    if t == "velocity":
        return f"more than {p['max_txns']} txns for one customer within {p['window_minutes']} min"
    if t == "odd_hour_high_amount":
        return (f"hour in [{p['start_hour']}, {p['end_hour']}) "
                f"and amount > {money(p['amount_threshold'])}")
    if t == "failed_then_success":
        return f">= {p['min_failures']} failed txns within {p['window_minutes']} min, then a success"
    if t == "structuring":
        return f"{money(p['lower'])} <= amount < {money(p['upper'])}"
    if t == "device_change_high_amount":
        return f"device differs from customer's previous txn and amount > {money(p['amount_threshold'])}"
    if t == "location_change":
        return f"location differs from customer's previous txn within {p['window_minutes']} min"
    if t == "repeat_beneficiary":
        return f"more than {p['max_txns']} txns to the same beneficiary within {p['window_minutes']} min"
    return rule["type"]


def table(headers, rows) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join(["---"] * len(headers)) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


MERMAID = """```mermaid
flowchart LR
  A[Transaction] --> B{Enabled rules R01-R08}
  B -->|any rule fires| C[Alert with rule IDs and severity]
  B -->|none fire| D[Pass through]
  C --> E[Analyst review queue]
  C --> F[Generated case summary]
  E --> G{Confirmed fraud?}
  G -->|yes| H[Feedback: tune thresholds]
  G -->|no| I[False positive: tune thresholds]
  H --> B
  I --> B
```"""


def main() -> int:
    tx = pd.read_csv("data/transactions.csv")
    rules = load_rules("rules/rules.json")
    uat = pd.read_csv("reports/uat_report.csv")
    base_perf = pd.read_csv("reports/rule_performance_baseline.csv")
    tuned_perf = pd.read_csv("reports/rule_performance_tuned.csv")
    sweep = pd.read_csv("reports/tuning_sweep.csv")

    with open("reports/summary_baseline.json", encoding="utf-8") as fh:
        base = json.load(fh)
    with open("reports/summary_tuned.json", encoding="utf-8") as fh:
        tuned = json.load(fh)
    with open("reports/iforest_summary.json", encoding="utf-8") as fh:
        iso = json.load(fh)

    rows = len(tx)
    fraud_rows = int(tx.is_fraud.sum())
    fraud_cases = int(tx.loc[tx.is_fraud == 1, "fraud_case_id"].nunique())
    names = {r["rule_id"]: r["name"] for r in rules}
    order = [r["rule_id"] for r in rules]

    parts: list[str] = []

    parts.append("# Transaction Monitoring Rule Engine\n")
    parts.append(
        "A JSON-configured transaction monitoring engine: eight rules, 10,000 "
        "synthetic transactions, 24 UAT acceptance cases, per-rule precision and "
        "false-positive measurement, a measured threshold-tuning trade-off, and a "
        "comparison against an unsupervised Isolation Forest.\n"
    )
    parts.append(
        "> **Synthetic data.** Every transaction in this repository is generated by "
        "`data/generate_data.py` with a fixed seed. No real customer data is used, "
        "no production system is touched, and the fraud patterns are hand-injected "
        "rather than observed.\n"
    )
    parts.append(
        "> **Generated document.** Every figure below is produced by "
        "`analysis/build_readme.py` from the CSV/JSON artefacts in `reports/`. "
        "Editing this file by hand would put it out of step with the run.\n"
    )

    # ---------------------------------------------------------------- headline
    parts.append("## Headline results\n")
    parts.append(table(
        ["Metric", "Baseline rules", "Tuned rules"],
        [
            ["Rules evaluated", base["rules_evaluated"], tuned["rules_evaluated"]],
            ["Alerts raised", base["alerts"], tuned["alerts"]],
            ["Alert precision", pct(base["precision_pct"]), pct(tuned["precision_pct"])],
            ["False positives", base["false_pos"], tuned["false_pos"]],
            ["FP rate (share of legitimate txns)", f"{base['fp_rate_pct']:.3f}%", f"{tuned['fp_rate_pct']:.3f}%"],
            ["Fraud cases caught",
             f"{base['fraud_cases_caught']}/{base['fraud_cases']} ({pct(base['recall_case_pct'])})",
             f"{tuned['fraud_cases_caught']}/{tuned['fraud_cases']} ({pct(tuned['recall_case_pct'])})"],
            ["Fraud transactions caught",
             f"{base['fraud_caught_txn']}/{base['fraud_txns']} ({pct(base['recall_txn_pct'])})",
             f"{tuned['fraud_caught_txn']}/{tuned['fraud_txns']} ({pct(tuned['recall_txn_pct'])})"],
        ],
    ))
    parts.append("")

    # --------------------------------------------------------------- quickstart
    parts.append("## Quick start\n")
    parts.append("""```powershell
python -m venv venv
.\\venv\\Scripts\\Activate.ps1        # Windows PowerShell
# source venv/bin/activate          # macOS / Linux
pip install -r requirements.txt

python -m data.generate_data        # 10,000 rows, 197 fraud
python -m engine.validate_rules     # fail loudly on bad rule config
python -m pytest -q                 # 24 UAT cases
python -m tests.make_uat_report     # reports/uat_report.csv
python -m analysis.evaluate         # per-rule precision, FP rate, alerts.csv
python -m analysis.tune             # threshold sweep -> rules_tuned.json
python -m analysis.evaluate rules/rules_tuned.json
python -m analysis.iforest_compare  # rules vs Isolation Forest
python -m analysis.build_readme     # regenerate this file
python -m analysis.check_contract   # guard the headline figures
```""")
    parts.append("")

    # ------------------------------------------------------------------ layout
    parts.append("## Repository layout\n")
    parts.append("""```
data/generate_data.py          seeded synthetic dataset (10,000 txns, 127 fraud cases)
rules/rules.json               8 rules, all thresholds externalised
rules/rules_tuned.json         same rules after the tuning sweep
engine/rule_engine.py          rule implementations + windowing, no hard-coded thresholds
engine/validate_rules.py       schema validation for rule configs
tests/cases.py                 24 UAT cases: positive / negative / boundary per rule
tests/test_rules.py            pytest parametrisation (24 collected tests)
tests/make_uat_report.py       pass/fail CSV artefact
analysis/evaluate.py           hits, precision, false-positive rate, recall
analysis/tune.py               threshold sweep + chosen tuned config
analysis/iforest_compare.py    Isolation Forest comparison
analysis/build_readme.py       this document
analysis/check_contract.py     asserts the figures quoted outside the repo
reports/                       generated artefacts (CSV + JSON)
```""")
    parts.append("")

    # ---------------------------------------------------------------- register
    parts.append("## Rules register\n")
    parts.append(
        f"{len(rules)} rules, all thresholds in JSON. Changing a threshold is a "
        "config change, not a code change, and requires no redeploy of the engine.\n"
    )
    reg_rows = []
    for r in rules:
        rid = r["rule_id"]
        reg_rows.append([
            rid, names[rid], condition(r), r["severity"].title(), RATIONALE[rid],
        ])
    parts.append(table(["ID", "Rule", "Condition", "Severity", "Rationale"], reg_rows))
    parts.append("")

    # --------------------------------------------------------------- semantics
    parts.append("## Boundary semantics\n")
    parts.append(
        "Threshold comparisons are strict (`>` not `>=`) and windows are trailing "
        "and inclusive of the boundary. This is a design decision, not an accident, "
        "because it gives every boundary case a defined answer that can be tested:\n"
    )
    parts.append(
        "- `amount > 25,000` means exactly 25,000 does **not** fire (UAT-R01-03).\n"
        "- A velocity window counts the current transaction, so `> 5 in 10 min` needs "
        "the 6th transaction to fire; exactly 5 does not (UAT-R02-03).\n"
        "- The odd-hour band is half-open `[start, end)`, so 05:00 is already business "
        "hours, not night.\n"
        "- The structuring band is `lower <= amount < upper`, so exactly 50,000 is "
        "outside the band (UAT-R05-03).\n"
        "- Location change is inclusive at the boundary: exactly 30 minutes apart "
        "still fires (UAT-R07-03).\n"
    )

    # ------------------------------------------------------------- performance
    parts.append("## Rule performance\n")
    parts.append(
        "Measured on the 10,000-row dataset with the baseline thresholds. "
        "`Precision` is true positives over rule hits; `FP rate` is false positives "
        "as a share of all legitimate transactions.\n"
    )
    merged = base_perf.merge(
        tuned_perf[["rule", "hits", "precision"]], on="rule", how="left",
        suffixes=("", "_tuned"),
    )
    perf_rows = []
    for _, row in merged.iterrows():
        rid = row["rule"]
        precision = "n/a" if pd.isna(row["precision"]) else f"{row['precision']:.1%}"
        precision_t = "n/a" if pd.isna(row["precision_tuned"]) else f"{row['precision_tuned']:.1%}"
        perf_rows.append([
            rid, names[rid], int(row["hits"]), precision, int(row["false_pos"]),
            f"{row['fp_rate_pct']:.3f}%", int(row["hits_tuned"]), precision_t,
        ])
    parts.append(table(
        ["ID", "Rule", "Hits", "Precision", "False pos", "FP rate", "Hits (tuned)", "Precision (tuned)"],
        perf_rows,
    ))
    parts.append("")
    parts.append(
        "The weakest rules are the ones whose *legitimate* behaviour overlaps the "
        "fraud pattern, not the ones with the most hits. R03 is noisy because genuine "
        "night payments were deliberately seeded into the data; R01 and R06 are noisy "
        "because a first payment to a new beneficiary and a new phone are ordinary "
        "events (rent, tuition, a handset upgrade) as well as fraud signals.\n"
    )
    parts.append(
        "Totals do not sum to 197 fraud transactions because rules overlap: R05 "
        "reports more true positives than the 25 rows injected for it, because a "
        "fraudulent 47,000 transfer on a changed device trips R05, R06 and R01 "
        "together. Counting each row once per rule is the point -- it shows which rule "
        "is doing the work.\n"
    )

    # ------------------------------------------------------------------ tuning
    parts.append("## Tuning: what changed and what it cost\n")
    parts.append(
        "Each row is a full engine run with one threshold changed. `Cases lost` "
        "counts fraud cases that the baseline caught and this variant misses -- the "
        "cost side of the trade-off.\n"
    )
    sweep_rows = []
    for _, row in sweep.iterrows():
        sweep_rows.append([
            row["variant"], int(row["alerts"]), pct(row["precision_pct"]),
            int(row["false_pos"]), f"{row['fp_rate_pct']:.3f}%",
            int(row["cases_caught"]), int(row["cases_lost"]),
        ])
    parts.append(table(
        ["Variant", "Alerts", "Precision", "False pos", "FP rate", "Cases caught", "Cases lost"],
        sweep_rows,
    ))
    parts.append("")
    shipped = sweep[sweep.variant.str.startswith("shipped")].iloc[0]
    aggressive = sweep[sweep.variant.str.startswith("aggressive")].iloc[0]
    fp_saved = base["false_pos"] - int(shipped["false_pos"])
    extra_fp = int(shipped["false_pos"]) - int(aggressive["false_pos"])
    extra_cases = int(aggressive["cases_lost"]) - int(shipped["cases_lost"])
    shipped_recall = shipped["cases_caught"] / base["fraud_cases"] * 100
    efficiency = fp_saved / max(int(shipped["cases_lost"]), 1)

    parts.append(
        f"The shipped configuration is the **efficient** point: R01 to 35,000, R06 "
        f"to 25,000 and R03 to 12,000. It removes {fp_saved} false positives, lifts "
        f"precision from {pct(base['precision_pct'])} to "
        f"{pct(shipped['precision_pct'])}, and costs {int(shipped['cases_lost'])} of "
        f"{base['fraud_cases']} fraud cases (case recall "
        f"{pct(base['recall_case_pct'])} -> {pct(shipped_recall)}). That works out at "
        f"about {efficiency:.0f} false positives removed per fraud case surrendered.\n"
    )
    parts.append(
        f"The last row is deliberately more aggressive: pushing R03 to 15,000 "
        f"instead of 12,000 removes {extra_fp} additional false positives but loses "
        f"{extra_cases} additional fraud cases -- roughly "
        f"{extra_fp / max(extra_cases, 1):.0f} false positives bought per case "
        f"surrendered, around {efficiency / max(extra_fp / max(extra_cases, 1), 0.01):.0f}x "
        f"worse than the shipped set. It is measured and reported, but not shipped: "
        f"the last few points of precision are paid for in missed fraud.\n"
    )
    parts.append(
        "The honest reading: raising a threshold does not remove fraud, it moves the "
        "cost. Every false positive avoided by lifting R01 also stops flagging the "
        "genuine large transfer that sits just under the new line. Case recall moves "
        "only slightly because of redundancy -- most fraud transactions already trip "
        "at least one other rule, so losing one signal rarely loses the case.\n"
    )

    # -------------------------------------------------------------------- iForest
    parts.append("## Rules vs Isolation Forest\n")
    parts.append(
        f"Same dataset, five features (`{', '.join(iso['features'])}`), "
        f"`contamination={iso['contamination']}`. The rule engine is evaluated at "
        "baseline thresholds so the comparison is like-for-like.\n"
    )
    parts.append(table(
        ["Measure", "Rule engine", "Isolation Forest"],
        [
            ["Alerts raised", iso["rule_alerts"], iso["ml_alerts"]],
            ["Fraud transactions caught",
             f"{iso['rules_fraud_txn']}/{iso['fraud_txns']}",
             f"{iso['ml_fraud_txn']}/{iso['fraud_txns']}"],
            ["Fraud cases caught",
             f"{iso['rules_cases']}/{iso['fraud_cases']} ({pct(iso['rules_case_recall_pct'])})",
             f"{iso['ml_cases']}/{iso['fraud_cases']} ({pct(iso['ml_case_recall_pct'])})"],
            ["Alerts overlapping the other method", iso["both"], iso["both"]],
            ["Unique alerts", iso["rules_only"], iso["ml_only"]],
            ["Fraud caught only by this method",
             iso["rules_only_fraud_txn"], iso["ml_only_fraud_txn"]],
        ],
    ))
    parts.append("")
    parts.append(
        "Rules are explainable: an alert names the rule and the threshold it crossed, "
        "which is what a review process needs. The Isolation Forest flags the "
        f"statistically unusual ({iso['ml_alerts']} alerts) but cannot say why, and "
        f"{iso['ml_only_fraud_txn']} fraud transactions were caught only by the model "
        f"against {iso['rules_only_fraud_txn']} caught only by the rules.\n"
    )
    parts.append(
        "The caveat worth stating out loud: `contamination=0.02` was set to the true "
        "fraud rate, which is knowledge you would not have in production. "
        "`analysis/iforest_compare.py` therefore also reports the model at 5% and 10% "
        "contamination in `reports/iforest_summary.json`.\n"
    )
    sens_rows = [[f"{s['contamination']:.0%}", s["alerts"], s["fraud_txn"],
                  f"{s['cases']}/{iso['fraud_cases']} ({pct(s['case_recall_pct'])})"]
                 for s in iso["sensitivity"]]
    parts.append(table(["Contamination", "Alerts", "Fraud txns", "Cases caught"], sens_rows))
    parts.append("")
    parts.append(
        "The practical read: rules for known patterns, the model as a second opinion "
        "for patterns nobody has written a rule for yet. Union of the two, ranked by "
        "severity, is the review queue.\n"
    )

    # ---------------------------------------------------------------------- UAT
    parts.append("## UAT summary\n")
    total_uat = len(uat)
    passed = int((uat.result == "PASS").sum())
    failed = total_uat - passed
    parts.append(
        f"{total_uat} acceptance cases, {uat.rule.nunique()} rules, three scenarios "
        f"each (positive, negative, boundary). Result: **{passed} passed, {failed} "
        f"failed**. Full detail in `reports/uat_report.csv`.\n"
    )
    uat_rows = []
    for rid in order:
        sub = uat[uat.rule == rid]
        cells = []
        for scenario in ("positive", "negative", "boundary"):
            chunk = sub[sub.scenario == scenario]
            cells.append(f"{int((chunk.result == 'PASS').sum())}/{len(chunk)}")
        rule_pass = int((sub.result == "PASS").sum())
        uat_rows.append([rid, names[rid], *cells,
                         "PASS" if rule_pass == len(sub) else "FAIL"])
    parts.append(table(
        ["ID", "Rule", "Positive", "Negative", "Boundary", "Verdict"], uat_rows,
    ))
    parts.append("")
    if failed == 0:
        parts.append(
            "All 24 cases passed on the first run of the suite. No defects were "
            "found by the acceptance tests, and none are claimed here -- inventing a "
            "bug to look thorough would be worse than reporting a clean run.\n"
        )
    else:
        parts.append(
            f"{failed} case(s) failed. Reproduce with `python -m pytest -q` and see "
            "`reports/uat_report.csv` for the expected/actual pairs.\n"
        )
    parts.append(
        "Two real limitations were found by *reviewing* the design rather than by "
        "tests failing, and they are documented in the limitations section below: "
        "the structuring rule is a single-transaction approximation, and "
        "transaction-level recall understates detection for burst rules.\n"
    )

    # ------------------------------------------------------------- decision flow
    parts.append("## Decision flow\n")
    parts.append(MERMAID)
    parts.append("")

    # ------------------------------------------------------------- limitations
    parts.append("## Limitations and known gaps\n")
    parts.append(
        f"- **Synthetic data.** {rows:,} generated transactions across "
        f"{tx.customer_id.nunique()} customers and 30 days, with "
        f"{fraud_rows} fraud rows in {fraud_cases} injected cases "
        f"({fraud_rows / rows * 100:.2f}% of rows). Real data has dirty timestamps, "
        "duplicate events, missing device and location fields, and far messier class "
        "imbalance.\n"
        "- **Structuring is approximated.** The rule flags a single transaction inside "
        "the band below the reporting limit. Genuine structuring is *repeated* "
        "sub-threshold activity that only looks suspicious in aggregate. The simple "
        "version is kept because the boundary is testable and the limitation is "
        "explainable; a production version would need a per-customer aggregation "
        "window.\n"
        "- **Transaction-level recall understates detection.** A velocity burst labels "
        "six rows fraud, but the rule fires once, on the sixth. That is why recall is "
        "reported per case as well as per row. The per-row figure is not a rule "
        "failure, it is a labelling artefact.\n"
        "- **Rules only see the fields they are given.** There is no behavioural "
        "baseline per customer (usual amount range, usual hours, usual beneficiaries), "
        "so a rule cannot tell that 20,000 is ordinary for one customer and extreme "
        "for another.\n"
        "- **Not real-time.** The engine evaluates a batch DataFrame. Streaming would "
        "need per-customer state stores for the velocity, repeat-beneficiary and "
        "failed-then-success windows.\n"
        "- **No case management.** Alerts are a CSV. There is no queue, no analyst "
        "disposition, no feedback loop back into tuning. The Mermaid diagram shows "
        "where that would sit.\n"
    )

    # ------------------------------------------------------------ design notes
    parts.append("## Design decisions\n")
    parts.append(
        "The questions this project is meant to survive, answered with its own "
        "numbers.\n"
    )
    parts.append(
        "- **Why JSON instead of hard-coded rules?** Thresholds change with fraud "
        "trends and analyst feedback, usually far more often than the code does. "
        "Keeping them in config means a tuning change is a reviewed file diff, "
        "`engine.validate_rules` catches typos that would otherwise silently produce "
        "zero alerts, and the engine can be exercised against several rule sets in "
        "one run -- which is exactly how `analysis/tune.py` measures the trade-off.\n"
        f"- **Why is {pct(base['recall_txn_pct'])} transaction recall not a failure?** "
        f"Per case it is {pct(base['recall_case_pct'])}. Burst rules alert on the "
        "triggering transaction, while the dataset labels every row in the burst as "
        "fraud. The measure an investigator cares about is whether the case was "
        "surfaced at all.\n"
        "- **What did tuning actually trade?** "
        f"{fp_saved} false positives removed, precision {pct(base['precision_pct'])} -> "
        f"{pct(tuned['precision_pct'])}, case recall {pct(base['recall_case_pct'])} -> "
        f"{pct(tuned['recall_case_pct'])}. Fewer alerts in the queue, at the price of "
        "no longer seeing the borderline cases. That is a business decision about "
        "analyst capacity, not a statistical one.\n"
        "- **Why do boundary tests matter?** They pin down the comparison operators. "
        "`>` versus `>=` is the difference between 25,000 being suspicious or not, and "
        "without a test that decision silently flips the first time someone "
        "refactors a rule.\n"
        "- **What breaks on real data?** Timezone-aware timestamps, duplicate events "
        "inflating velocity counts, missing device IDs making `shift()` comparisons "
        "meaningless, and volumes that need the O(n) window loops replaced with "
        "indexed lookups. The rule logic survives; the plumbing does not.\n"
        "- **Why not just use the Isolation Forest?** Explainability and control. An "
        "alert that names the rule and the crossed threshold can be defended to a "
        "customer or a regulator; `anomaly score 0.61` cannot. The model is useful "
        "for finding patterns nobody has written a rule for yet.\n"
    )

    # ------------------------------------------------------------------- repro
    parts.append("## Reproducing the figures\n")
    parts.append(
        "Everything is seeded (`numpy.random.default_rng(42)` for the data, "
        "`random_state=42` for the model), so a clean checkout reproduces these exact "
        "numbers. `python -m analysis.check_contract` asserts the headline counts "
        f"({rows:,} rows, {fraud_rows} fraud rows, {fraud_cases} fraud cases, "
        f"{len(rules)} rules, {total_uat} UAT cases) and exits non-zero if any drift.\n"
    )

    Path("README.md").write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote README.md ({len('\n'.join(parts).splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
